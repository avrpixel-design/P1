# NEW FIGURE 2: Pairwise independence matrix with effect-size annotation
# ════════════════════════════════════════════════════════════════════════════

def fig_pairwise_independence(results, save_path):
    """
    Symmetric 5×5 matrix of all feature-set pairs (s, f, e, l, p) showing MI
    in the lower triangle and a qualitative independence badge in the upper.
    Inspired by NeurIPS correlation-matrix figures.
    """
    feature_keys = ['source', 'filter', 'emotional', 'linguistic', 'pathological']
    labels = ['Source', 'Filter', 'Emotional', 'Linguistic', 'Pathological']
    short = ['s', 'f', 'e', 'l', 'p']
    n = len(labels)

    from itertools import combinations

    # ── Compute KSG MI for all 10 unique pairs, averaged across combos ──
    from scipy.special import digamma
    from scipy.spatial import cKDTree

    class _KSG:
        def __init__(self, k=5):
            self.k = k
        def estimate(self, x, y):
            nn = x.shape[0]
            if nn < self.k + 1: return 0.0
            x = (x - x.mean(0)) / (x.std(0) + 1e-10)
            y = (y - y.mean(0)) / (y.std(0) + 1e-10)
            xy = np.hstack([x, y])
            tree_xy = cKDTree(xy); tree_x = cKDTree(x); tree_y = cKDTree(y)
            d, _ = tree_xy.query(xy, k=self.k+1, p=np.inf)
            eps = d[:, -1]
            nx = np.array([len(tree_x.query_ball_point(x[i], eps[i]-1e-10, p=np.inf))-1 for i in range(nn)])
            ny = np.array([len(tree_y.query_ball_point(y[i], eps[i]-1e-10, p=np.inf))-1 for i in range(nn)])
            nx, ny = np.maximum(nx, 1), np.maximum(ny, 1)
            return max(0.0, digamma(self.k)+digamma(nn)-np.mean(digamma(nx+1)+digamma(ny+1)))

    ksg = _KSG(k=5)
    from sklearn.preprocessing import StandardScaler
    scaler = StandardScaler()

    mi_matrix = np.full((n, n), np.nan)
    for ci, cj in combinations(range(n), 2):
        vals = []
        for combo_data in results.values():
            feats = combo_data['features']
            x = feats.get(feature_keys[ci])
            y = feats.get(feature_keys[cj])
            if x is not None and y is not None:
                nn = min(len(x), len(y))
                xn = scaler.fit_transform(x[:nn])
                yn = scaler.fit_transform(y[:nn])
                vals.append(ksg.estimate(xn, yn))
        if vals:
            mi_matrix[ci, cj] = np.mean(vals)
            mi_matrix[cj, ci] = np.mean(vals)
    np.fill_diagonal(mi_matrix, np.nan)

    # ── Plot ──
    fig, ax = plt.subplots(figsize=(FIG_WIDTH_SINGLE + 0.8, FIG_WIDTH_SINGLE + 0.5))

    cmap = LinearSegmentedColormap.from_list('indep', ['#E8F5E9', '#FFECB3', '#FFCDD2'], N=256)
    vmax = max(1.0, np.nanmax(mi_matrix))
    masked = np.ma.masked_invalid(mi_matrix)

    im = ax.imshow(masked, cmap=cmap, vmin=0, vmax=vmax, aspect='equal')

    # ── Annotations: lower triangle = MI value, upper triangle = badge ──
    for i in range(n):
        for j in range(n):
            if i == j:
                ax.text(j, i, f'{short[i]}', ha='center', va='center',
                        fontsize=11, fontweight='bold', color='#333', style='italic')
            elif i > j:  # lower triangle → MI value
                val = mi_matrix[i, j]
                if not np.isnan(val):
                    ax.text(j, i, f'{val:.2f}', ha='center', va='center', fontsize=8,
                            fontweight='bold', color='#333')
            else:  # upper triangle → badge
                val = mi_matrix[i, j]
                if not np.isnan(val):
                    if val < 0.15:
                        badge, bcol = '✓ Indep.', '#2E7D32'
                    elif val < 0.5:
                        badge, bcol = '~ Weak', '#F57F17'
                    else:
                        badge, bcol = '✗ Coupled', '#C62828'
                    ax.text(j, i, badge, ha='center', va='center',
                            fontsize=6.5, fontweight='bold', color=bcol)

    # ── Grid ──
    for x in np.arange(-0.5, n, 1):
        ax.axvline(x, color='white', linewidth=1.5)
        ax.axhline(x, color='white', linewidth=1.5)

    ax.set_xticks(range(n))
    ax.set_xticklabels(labels, fontsize=8, fontweight='bold')
    ax.set_yticks(range(n))
    ax.set_yticklabels(labels, fontsize=8, fontweight='bold')
    ax.tick_params(length=0)

    cbar = fig.colorbar(im, ax=ax, shrink=0.7, pad=0.04)
    cbar.set_label('MI (nats)', fontsize=8)
    cbar.ax.tick_params(labelsize=6)

