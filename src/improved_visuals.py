def table_estimator_diagnostics(results, output_dir):
    """
    Diagnostic table: per dimension pair, reports estimator-level statistics
    including convergence rate, KSG weight used, MINE–KSG deviation,
    CLUB–KSG deviation, and bound tightness ratio.
    """
    pairs = ['Emotion-Linguistic', 'Emotion-Pathology', 'Linguistic-Pathology', 'Source-Filter']
    rows = []

    for p in pairs:
        mine_vals, club_vals, ksg_vals, final_vals, conv_rates = [], [], [], [], []
        for data in results.values():
            mi = data['mi_results'].get(p)
            if mi is None:
                continue
            mine_vals.append(mi['mine_mean'])
            club_vals.append(mi['club_mean'])
            ksg_vals.append(mi['ksg_mean'])
            final_vals.append(mi['combined_mean'])
            n_conv = mi.get('n_converged', 0)
            n_total = len(mi.get('convergence', []))
            conv_rates.append(n_conv / n_total if n_total > 0 else 0)

        if not mine_vals:
            continue

        mine_m, club_m, ksg_m = np.mean(mine_vals), np.mean(club_vals), np.mean(ksg_vals)
        delta = club_m - mine_m
        # KSG weight: from adaptive weighting formula
        w_ksg = min(0.6, 0.3 + delta * 0.1) if delta > 1.0 else 0.3
        # Bound tightness: ratio of gap to final estimate
        final_m = np.mean(final_vals)
        tightness = delta / final_m if final_m > 0.01 else float('inf')

        rows.append({
            'Pair': p,
            'MINE (mean)': f"{mine_m:.3f}",
            'CLUB (mean)': f"{club_m:.3f}",
            'KSG (mean)': f"{ksg_m:.3f}",
            'Δ (gap)': f"{delta:.3f}",
            'w_KSG': f"{w_ksg:.2f}",
            '|MINE−KSG|': f"{abs(mine_m - ksg_m):.3f}",
            '|CLUB−KSG|': f"{abs(club_m - ksg_m):.3f}",
            'Tightness (Δ/Final)': f"{tightness:.2f}" if tightness < 100 else '—',
            'Conv. rate': f"{np.mean(conv_rates):.0%}",
        })

    df = pd.DataFrame(rows)
    csv_path = os.path.join(output_dir, 'P1_table_estimator_diagnostics.csv')
    df.to_csv(csv_path, index=False)

    # ── LaTeX ──
    latex = r"""\begin{table}[t]
\centering
\caption{Estimator diagnostics: convergence, adaptive weighting, and bound agreement. $w_\text{KSG}$ = KSG anchor weight in Eq.~(11). Tightness = $\Delta / \hat{I}_\text{final}$ (lower is better).}
\label{tab:diagnostics}
\resizebox{\columnwidth}{!}{%
\begin{tabular}{lccccccc}
\toprule
\textbf{Pair} & $\boldsymbol{\Delta}$ & $\boldsymbol{w_\text{KSG}}$ & $|\text{MINE}{-}\text{KSG}|$ & $|\text{CLUB}{-}\text{KSG}|$ & \textbf{Tightness} & \textbf{Conv.\ rate} \\
\midrule
"""
    for _, row in df.iterrows():
        pair_fmt = row['Pair'].replace('-', '--')
        latex += (f"{pair_fmt} & {row['Δ (gap)']} & {row['w_KSG']} & "
                  f"{row['|MINE−KSG|']} & {row['|CLUB−KSG|']} & "
                  f"{row['Tightness (Δ/Final)']} & {row['Conv. rate']} \\\\\n")

    latex += r"""\bottomrule
\end{tabular}}
\end{table}
"""
    tex_path = os.path.join(output_dir, 'P1_table_estimator_diagnostics.tex')
    with open(tex_path, 'w') as f:
        f.write(latex)

    logger.info(f"  Saved: {csv_path}")
    logger.info(f"  Saved: {tex_path}")
    return df


