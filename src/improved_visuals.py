# HELPER: safe combo label
# ════════════════════════════════════════════════════════════════════════════
def _combo_label(combo: str) -> str:
    protected = {'L2-ARCTIC': 'L2__ARCTIC', 'UA-Speech': 'UA__Speech', 'MDVR-KCL': 'MDVR__KCL'}
    safe = combo
    for k, v in protected.items():
        safe = safe.replace(k, v)
    parts = [p.replace('__', '-').replace('_', ' ') for p in safe.split('-') if p]
    return ', '.join(parts)


def _short_combo(combo: str) -> str:
    """Very short 3-letter abbreviation per dataset."""
    protected = {'L2-ARCTIC': 'L2A', 'UA-Speech': 'UAS', 'MDVR-KCL': 'MKC',
                 'RAVDESS': 'RAV', 'IEMOCAP': 'IEM', 'GMU': 'GMU'}
    label = combo
    for full, abbr in protected.items():
        label = label.replace(full, abbr)
    parts = [p for p in label.split('-') if p]
    return '-'.join(parts[:3])


