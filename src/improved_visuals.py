# NEW FIGURE 1: Radar chart — estimator agreement per dimension pair
# ════════════════════════════════════════════════════════════════════════════

def fig_radar_estimator_agreement(results, save_path):
    """
    Radar chart showing how tightly MINE, CLUB, and KSG agree for each pair.
    Each spoke = a dimension pair; each polygon = an estimator.
    Reveals at a glance where bounds are tight vs. divergent.
    """
    pairs = ['Emotion-Linguistic', 'Emotion-Pathology', 'Linguistic-Pathology', 'Source-Filter']
    pair_labels = ['Emo–Ling', 'Emo–Path', 'Ling–Path', 'Src–Flt']
    estimators = [('mine_mean', 'MINE', COLORS['MINE']),
                  ('club_mean', 'CLUB', COLORS['CLUB']),
                  ('ksg_mean',  'KSG',  COLORS['KSG']),
                  ('combined_mean', 'Final', COLORS['Final'])]

    # ── Aggregate means ──
    agg = {p: {} for p in pairs}
    for p in pairs:
        for key, _, _ in estimators:
            vals = [d['mi_results'][p][key] for d in results.values() if p in d['mi_results']]
            agg[p][key] = np.mean(vals) if vals else 0.0

    n_spokes = len(pairs)
    angles = np.linspace(0, 2 * np.pi, n_spokes, endpoint=False).tolist()
    angles += angles[:1]  # close polygon

    fig, ax = plt.subplots(figsize=(FIG_WIDTH_SINGLE + 0.3, FIG_WIDTH_SINGLE + 0.3),
                           subplot_kw=dict(polar=True))

    vmax = max(agg[p][k] for p in pairs for k, _, _ in estimators) * 1.25

    for key, label, color in estimators:
        values = [agg[p][key] for p in pairs]
        values += values[:1]
        lw = 2.0 if label == 'Final' else 1.2
        ls = '-' if label == 'Final' else '--'
        ax.plot(angles, values, color=color, linewidth=lw, linestyle=ls, label=label)
        ax.fill(angles, values, color=color, alpha=0.06)

    # ── Spoke labels ──
    ax.set_xticks(angles[:-1])
    ax.set_xticklabels(pair_labels, fontsize=8, fontweight='bold')
    ax.set_ylim(0, vmax)
    ax.set_yticks(np.arange(0, vmax, 0.2))
    ax.set_yticklabels([f'{v:.1f}' for v in np.arange(0, vmax, 0.2)], fontsize=6, color='grey')
    ax.yaxis.set_label_position('left')

    # ── Independence threshold ring ──
    threshold = 0.15
    theta_ring = np.linspace(0, 2 * np.pi, 100)
    ax.plot(theta_ring, [threshold] * 100, color=COLORS['Threshold'],
            linestyle=':', linewidth=1.5, alpha=0.7, label='Independence\nthreshold (0.15)')

    ax.legend(loc='center left', bbox_to_anchor=(1.18, 0.5), ncol=1,
              fontsize=6.8, frameon=False, borderaxespad=0.3)
    ax.set_title('Estimator Agreement\nAcross Dimension Pairs', fontsize=10,
                 fontweight='bold', pad=20)

    plt.tight_layout(rect=[0, 0, 0.82, 1])
    plt.savefig(save_path, dpi=300, bbox_inches='tight', facecolor='white')
    plt.close()
    logger.info(f"  Saved: {save_path}")


