def fig3_attribution(results, save_path):
    """Figure 3: Source-filter attribution butterfly chart with per-combo jitter."""
    dimensions = ['Emotional', 'Linguistic', 'Pathological']
    dim_colors = [COLORS['Emotional'], COLORS['Linguistic'], COLORS['Pathological']]
    font_size = 9

    # ── Aggregate per-combo source proportions ──
    attr_data = {d: [] for d in dimensions}
    for data in results.values():
        for dim in dimensions:
            if dim in data['attribution']:
                attr_data[dim].append(data['attribution'][dim]['source'])

    stats_data = {}
    for dim in dimensions:
        vals = attr_data[dim]
        if vals:
            m, s = np.mean(vals), np.std(vals)
            n = len(vals)
            ci = stats.t.ppf(0.975, df=max(n - 1, 1)) * s / np.sqrt(n) if n > 1 else 0
            stats_data[dim] = {'mean': m, 'std': s, 'ci': ci, 'n': n, 'vals': vals}

    if not stats_data:
        return

    fig, ax = plt.subplots(figsize=(FIG_WIDTH_SINGLE + 0.6, 2.8))
    y_pos = np.arange(len(dimensions))
    bar_h = 0.56

    for i, (dim, col) in enumerate(zip(dimensions, dim_colors)):
        if dim not in stats_data:
            continue
        sd = stats_data[dim]
        src_m = sd['mean']
        flt_m = 1 - src_m

        # ── Source bar (left of midpoint 0.5 → grows right) ──
        ax.barh(y_pos[i], src_m, height=bar_h, left=0, color=COLORS['Source'],
                alpha=0.88, edgecolor='#444', linewidth=0.5,
                label='Source (Glottal)' if i == 0 else None)
        # ── Filter bar (right portion) ──
        ax.barh(y_pos[i], flt_m, height=bar_h, left=src_m, color=COLORS['Filter'],
                alpha=0.88, edgecolor='#444', linewidth=0.5,
                label='Filter (Vocal Tract)' if i == 0 else None)

        # ── Per-combination jitter points ──
        jitter = np.random.default_rng(42).normal(0, 0.06, len(sd['vals']))
        ax.scatter(sd['vals'], y_pos[i] + jitter, s=12, color=col,
                   edgecolor='white', linewidth=0.3, zorder=5, alpha=0.8)

        # ── CI whisker on the source proportion ──
        ax.errorbar(src_m, y_pos[i], xerr=sd['ci'], fmt='|', color='black',
                    capsize=4, capthick=1.2, linewidth=1.2, zorder=6)

        # ── Labels ──
        label_y = y_pos[i] - (bar_h / 2 + 0.08)
        ax.text(src_m / 2, label_y, f'{src_m:.0%}', ha='center', va='bottom',
            fontsize=font_size * 0.5, fontweight='bold', color='black')
        ax.text(src_m + flt_m / 2, label_y, f'{flt_m:.0%}', ha='center', va='bottom',
            fontsize=font_size * 0.5, fontweight='bold', color='black')

        # ── Interpretation badge ──
        interp = 'Source-dom.' if src_m > 0.55 else ('Filter-dom.' if src_m < 0.45 else 'Balanced')
        badge_col = COLORS['Source'] if src_m > 0.55 else (COLORS['Filter'] if src_m < 0.45 else '#888')
        ax.annotate(interp, xy=(1.02, y_pos[i]), xycoords=('axes fraction', 'data'),
                    fontsize=font_size, color=badge_col, fontweight='bold', va='center')

    # ── 50% reference line ──
    ax.axvline(0.5, color='black', linestyle=':', linewidth=0.8, alpha=0.5, zorder=0)

    ax.set_xlim(0, 1)
    ax.set_ylim(-0.85, len(dimensions) - 0.5)
    ax.set_yticks(y_pos)
    ax.set_yticklabels(['e', 'l', 'p'], fontsize=font_size, fontweight='bold', color='black')
    for tick_label in ax.get_yticklabels():
        tick_label.set_ha('center')
    ax.set_xlabel('Attribution Proportion', fontsize=font_size, fontweight='bold')
    ax.set_xticks([0, 0.25, 0.5, 0.75, 1.0])
    ax.set_xticklabels(['0%', '25%', '50%', '75%', '100%'], fontsize=font_size)
    ax.invert_yaxis()

    # ── Legends (center-aligned): Row 1 source/filter; Row 2 per-dimension circles ──
    legend_row1 = ax.legend(
        handles=[
            mpatches.Patch(color=COLORS['Source'], label='Source (Glottal)'),
            mpatches.Patch(color=COLORS['Filter'], label='Filter (Vocal Tract)'),
        ],
        loc='upper center',
        bbox_to_anchor=(0.5, 1.45),
        ncol=2,
        fontsize=font_size,
        frameon=False,
        columnspacing=0.9,
        handletextpad=0.4,
    )
    legend_row1._legend_box.align = "center"

    legend_row2 = ax.legend(
        handles=[
            plt.Line2D([], [], marker='o', color=dim_colors[0], markerfacecolor=dim_colors[0],
                       markeredgecolor='white', markeredgewidth=0.3, markersize=5,
                       linestyle='', label='Emotional (e)'),
            plt.Line2D([], [], marker='o', color=dim_colors[1], markerfacecolor=dim_colors[1],
                       markeredgecolor='white', markeredgewidth=0.3, markersize=5,
                       linestyle='', label='Linguistic (l)'),
            plt.Line2D([], [], marker='o', color=dim_colors[2], markerfacecolor=dim_colors[2],
                       markeredgecolor='white', markeredgewidth=0.3, markersize=5,
                       linestyle='', label='Pathological (p)'),
        ],
        loc='upper center',
        bbox_to_anchor=(0.5, 1.30),
        ncol=3,
        fontsize=font_size,
        frameon=False,
        columnspacing=0.8,
        handletextpad=0.35,
    )
    legend_row2._legend_box.align = "center"
    ax.add_artist(legend_row1)

    plt.tight_layout(rect=[0, 0, 0.92, 0.72])
    plt.savefig(save_path, dpi=300, bbox_inches='tight', pad_inches=0.16, facecolor='white')
    plt.close()
